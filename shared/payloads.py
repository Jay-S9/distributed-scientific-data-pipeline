# ==========================================================
# Payload Models
# ----------------------------------------------------------
# These models define the scientific data carried
# inside a ScientificEvent.
# ==========================================================

from pydantic import BaseModel, Field
from shared.constants import SignalQuality, DetectorStatus

class SyntheticPayload(BaseModel):
    """
    Payload generated by the synthetic radiation detector.
    """

    detector_id: str = Field(
        ...,
        description="Identifier of the detector."
    )

    energy: float = Field(
        ...,
        description="Measured particle energy."
    )

    unit: str = Field(
        default="MeV",
        description="Unit of the energy measurement."
    )

    signal_quality: SignalQuality = Field(
        ...,
        description="Quality of the recorded signal."
    )

    status: DetectorStatus = Field(
        default=DetectorStatus.OK,
        description="Current detector health."
    )