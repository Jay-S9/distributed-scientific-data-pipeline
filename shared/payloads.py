# ==========================================================
# Payload Models
# ----------------------------------------------------------
# These models define the scientific data carried
# inside a ScientificEvent.
# ==========================================================

from pydantic import BaseModel, Field
from shared.constants import SignalQuality, DetectorStatus


class SyntheticPayload(BaseModel):
    """
    Payload generated by the synthetic radiation detector.
    """

    detector_id: str = Field(
        ...,
        description="Identifier of the detector."
    )

    energy: float = Field(
        ...,
        description="Measured particle energy."
    )

    unit: str = Field(
        default="MeV",
        description="Unit of the energy measurement."
    )

    signal_quality: SignalQuality = Field(
        ...,
        description="Quality of the recorded signal."
    )

    status: DetectorStatus = Field(
        default=DetectorStatus.OK,
        description="Current detector health."
    )


class ParticleMeasurement(BaseModel):
    """
    Kinematic measurement of one particle
    from the MuRun2010B dataset.
    """

    particle_type: str = Field(
        ...,
        description="Particle type recorded by the dataset."
    )

    energy: float = Field(
        ...,
        description="Particle energy."
    )

    px: float = Field(
        ...,
        description="Momentum component along x."
    )

    py: float = Field(
        ...,
        description="Momentum component along y."
    )

    pz: float = Field(
        ...,
        description="Momentum component along z."
    )

    pt: float = Field(
        ...,
        description="Transverse momentum."
    )

    eta: float = Field(
        ...,
        description="Pseudorapidity."
    )

    phi: float = Field(
        ...,
        description="Azimuthal angle."
    )

    charge: int = Field(
        ...,
        description="Particle electric charge."
    )


class MuRun2010BPayload(BaseModel):
    """
    Scientific payload representing one event
    from the MuRun2010B dataset.
    """

    run: int = Field(
        ...,
        description="Run identifier."
    )

    event: int = Field(
        ...,
        description="Event identifier from the dataset."
    )

    particle_1: ParticleMeasurement = Field(
        ...,
        description="First particle measurement."
    )

    particle_2: ParticleMeasurement = Field(
        ...,
        description="Second particle measurement."
    )

    invariant_mass: float = Field(
        ...,
        description="Invariant mass M of the particle pair."
    )